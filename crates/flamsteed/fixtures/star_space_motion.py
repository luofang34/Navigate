"""Write star-space-motion.txt: J2000 star directions under straight-line space motion.

python3 -I star_space_motion.py catalog star-space-motion.txt

The input is CDS V/50 `catalog` (SHA-256
69797549cc1605aad7ff94e9325e29a1661f2a253917faaa056d9bf20b809afd). The
stars are the 20 brightest, the 10 with the largest proper motion, and the 10
with the largest radial term (radial velocity times parallax). Each star
moves on a straight line in space from its J2000 position: the proper motion
across the line of sight, and the radial velocity along it when the
catalogue gives a trigonometric parallax. Both scale by the light-time
factor 1 / (1 - v_r / c), which turns the observed rates into space motion
(Stumpff 1985; SOFA eraStarpv). Rows give the HR number, Julian years from
J2000, the unit direction, and the barycentric position in parsecs, or nan
without a parallax.
"""
import math
import sys

catalog, out = sys.argv[1:3]
MAS = math.pi / 648e6
PARSEC_PER_YEAR_PER_KM_S = 1.0227121650537077e-6
LIGHT_SPEED_KM_S = 299792.458
EPOCHS = [-2000.0, -331.0, 1000.0, 1700.0, 3000.0]

stars = []
for line in open(catalog):
    if not line[75:77].strip():
        continue
    ra = math.radians((int(line[75:77]) + int(line[77:79]) / 60 + float(line[79:83]) / 3600) * 15)
    dec = math.radians(int(line[84:86]) + int(line[86:88]) / 60 + int(line[88:90]) / 3600)
    dec = -dec if line[83] == '-' else dec
    pm_ra, pm_dec = float(line[148:154]) * 1000, float(line[154:160]) * 1000
    parallax = float(line[161:166]) * 1000 if line[161:166].strip() and line[160] != 'D' else 0.0
    rv = float(line[166:170]) if line[166:170].strip() else 0.0
    stars.append((int(line[0:4]), ra, dec, pm_ra, pm_dec, parallax, rv, float(line[102:107])))

brightest = sorted(stars, key=lambda s: s[7])[:20]
fastest = sorted(stars, key=lambda s: -math.hypot(s[3], s[4]))[:10]
radial = sorted(stars, key=lambda s: -abs(s[5] * s[6]))[:10]
chosen = sorted({s[0]: s for s in brightest + fastest + radial}.values())


def position(star, years):
    """The position in units of the J2000 distance."""
    _, ra, dec, pm_ra, pm_dec, parallax, rv, _ = star
    p = (math.cos(dec) * math.cos(ra), math.cos(dec) * math.sin(ra), math.sin(dec))
    east = (-math.sin(ra), math.cos(ra), 0.0)
    north = (-math.sin(dec) * math.cos(ra), -math.sin(dec) * math.sin(ra), math.cos(dec))
    k = 1.0 / (1.0 - rv / LIGHT_SPEED_KM_S) if parallax > 0 else 1.0
    rate = rv * parallax / 1000.0 * PARSEC_PER_YEAR_PER_KM_S
    return [p[i] * (1.0 + k * rate * years) + k * (east[i] * pm_ra + north[i] * pm_dec) * MAS * years
            for i in range(3)]


with open(out, 'w') as f:
    f.write('# Generated by crates/flamsteed/fixtures/star_space_motion.py.\n')
    f.write('# hr years_from_j2000 x y z position_x_pc position_y_pc position_z_pc\n')
    for star in chosen:
        for year in EPOCHS:
            v = position(star, year - 2000.0)
            n = math.sqrt(sum(c * c for c in v))
            x, y, z = (c / n for c in v)
            distance = 1000.0 / star[5] if star[5] > 0 else float('nan')
            px, py, pz = (c * distance for c in v)
            f.write(f'{star[0]} {year - 2000.0!r} {x!r} {y!r} {z!r} {px!r} {py!r} {pz!r}\n')
