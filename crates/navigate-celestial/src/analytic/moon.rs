//! Geocentric Moon from Meeus, *Astronomical Algorithms* (2nd ed.), chapter 47.
//!
//! The series is a truncation of ELP-2000/82 (Chapront-Touzé and Chapront).
//! Meeus gives its accuracy as 10 arcseconds in longitude and 4 arcseconds
//! in latitude. The coefficients come from the `moonposition` package of
//! `github.com/soniakeys/meeus`, Copyright 2013 Sonia Keys, MIT License.

/// Geocentric longitude and latitude in radians and distance in metres,
/// in the mean ecliptic and equinox of date, without nutation. `t` is
/// TDB Julian centuries from J2000.
pub(crate) fn geocentric(t: f64) -> (f64, f64, f64) {
    let mean_longitude = degrees(
        t,
        &[
            218.316_447_7,
            481_267.881_234_21,
            -0.001_578_6,
            1.0 / 538_841.0,
            -1.0 / 65_194_000.0,
        ],
    );
    let arguments = [
        degrees(
            t,
            &[
                297.850_192_1,
                445_267.111_403_4,
                -0.001_881_9,
                1.0 / 545_868.0,
                -1.0 / 113_065_000.0,
            ],
        ),
        degrees(
            t,
            &[
                357.529_109_2,
                35_999.050_290_9,
                -0.000_153_5,
                1.0 / 24_490_000.0,
            ],
        ),
        degrees(
            t,
            &[
                134.963_396_4,
                477_198.867_505_5,
                0.008_741_4,
                1.0 / 69_699.0,
                -1.0 / 14_712_000.0,
            ],
        ),
        degrees(
            t,
            &[
                93.272_095,
                483_202.017_523_3,
                -0.003_653_9,
                -1.0 / 3_526_000.0,
                1.0 / 863_310_000.0,
            ],
        ),
    ];
    let [a1, a2, a3] = [
        degrees(t, &[119.75, 131.849]),
        degrees(t, &[53.09, 479_264.29]),
        degrees(t, &[313.45, 481_266.484]),
    ];
    let f = arguments[3];
    // Terms that contain the solar anomaly M decrease with the Earth's orbital eccentricity.
    let eccentricity = 1.0 + t * (-0.002_516 - t * 0.000_007_4);
    let scale = |multiples: &[i8; 4]| eccentricity.powi(i32::from(multiples[1].unsigned_abs()));
    let argument = |multiples: &[i8; 4]| {
        multiples
            .iter()
            .zip(arguments)
            .map(|(multiple, angle)| f64::from(*multiple) * angle)
            .sum::<f64>()
    };

    let mut longitude = 3958.0 * a1.sin() + 1962.0 * (mean_longitude - f).sin() + 318.0 * a2.sin();
    let mut distance = 0.0;
    for (multiples, sine, cosine) in &LONGITUDE_DISTANCE {
        let (sin, cos) = argument(multiples).sin_cos();
        longitude += sine * sin * scale(multiples);
        distance += cosine * cos * scale(multiples);
    }
    let mut latitude = -2235.0 * mean_longitude.sin()
        + 382.0 * a3.sin()
        + 175.0 * (a1 - f).sin()
        + 175.0 * (a1 + f).sin()
        + 127.0 * (mean_longitude - arguments[2]).sin()
        - 115.0 * (mean_longitude + arguments[2]).sin();
    for (multiples, sine) in &LATITUDE {
        latitude += sine * argument(multiples).sin() * scale(multiples);
    }
    // Sums are in micro-degrees and metres.
    (
        mean_longitude + (longitude * 1e-6).to_radians(),
        (latitude * 1e-6).to_radians(),
        385_000_560.0 + distance,
    )
}

/// A polynomial in `t` with coefficients in degrees, returned in radians.
fn degrees(t: f64, coefficients: &[f64]) -> f64 {
    coefficients
        .iter()
        .rev()
        .fold(0.0, |total, coefficient| total * t + coefficient)
        .to_radians()
}

