"""Write skyfield-stars.txt: apparent BSC5 star directions in ITRS axes.

uv run --no-project --python 3.13 --with skyfield==1.53 python -I \
    skyfield_stars.py catalog de421.bsp skyfield-stars.txt

The inputs are CDS V/50 `catalog` and NAIF `de421.bsp`. The ITRS axes use
the Skyfield built-in IERS UT1 and no polar motion.
"""
import sys
from skyfield.api import load, Star
from skyfield.framelib import itrs
catalog, de421, out = sys.argv[1:4]
ts = load.timescale(builtin=True)
eph = load(de421)
earth = eph['earth']
stars = []
for line in open(catalog):
    if not line[75:77].strip():
        continue
    hr = int(line[0:4])
    ra_h = int(line[75:77]) + int(line[77:79]) / 60 + float(line[79:83]) / 3600
    dec = int(line[84:86]) + int(line[86:88]) / 60 + int(line[88:90]) / 3600
    dec = -dec if line[83] == '-' else dec
    vmag = float(line[102:107])
    pm_ra, pm_dec = float(line[148:154]) * 1000, float(line[154:160]) * 1000
    stars.append((hr, ra_h, dec, pm_ra, pm_dec, vmag))
pick = {424, 7228, 8085, 8086, 5340, 5459, 6879}
chosen = [s for i, s in enumerate(stars) if s[5] <= 1.5 or s[0] in pick or i % 450 == 0]
times = ts.utc([1975, 1990, 2000, 2010, 2020, 2026], [3, 7, 1, 10, 4, 6], [1, 15, 1, 20, 5, 14], [0, 6, 12, 18, 3, 9], [0, 0, 0, 0, 0, 19], [0, 0, 0, 0, 0, 41])
with open(out, 'w') as f:
    f.write('# Generated by crates/navigate-celestial/fixtures/skyfield_stars.py with Skyfield 1.53.\n')
    f.write('# Apparent star directions, ITRS axes with built-in IERS UT1, no polar motion.\n')
    f.write('# hr tdb_s x y z\n')
    for t in times:
        tdb_s = float((t.tdb - 2451545.0) * 86400.0)
        observer = earth.at(t)
        for hr, ra_h, dec, pm_ra, pm_dec, _ in chosen:
            star = Star(ra_hours=ra_h, dec_degrees=dec, ra_mas_per_year=pm_ra, dec_mas_per_year=pm_dec)
            x, y, z = (float(c) for c in observer.observe(star).apparent().frame_xyz(itrs).au)
            n = (x * x + y * y + z * z) ** 0.5
            f.write(f'{hr} {tdb_s!r} {x / n!r} {y / n!r} {z / n!r}\n')
