"""Write erfa-ltp.txt: ERFA long-term precession matrices, J2000 to date.

uv run --no-project --python 3.13 --with pyerfa==2.0.1.5 python -I erfa_ltp.py erfa-ltp.txt

Each row is a Julian epoch (TT), then the nine elements of `erfa.ltp` in row
order.
"""
import sys
import erfa

out = sys.argv[1]
epochs = [-2000.0, -1000.0, 0.0, 500.0, 1000.0, 1500.0, 1800.0, 1900.0, 2000.0, 2026.5, 2100.0, 2200.0, 2500.0, 3000.0]
with open(out, 'w') as f:
    f.write(f'# Generated by crates/navigate-celestial/fixtures/erfa_ltp.py with pyerfa {erfa.__version__}.\n')
    f.write('# julian_epoch r00 r01 r02 r10 r11 r12 r20 r21 r22\n')
    for epoch in epochs:
        matrix = erfa.ltp(epoch)
        f.write(' '.join([repr(epoch)] + [repr(float(x)) for x in matrix.flatten()]) + '\n')
