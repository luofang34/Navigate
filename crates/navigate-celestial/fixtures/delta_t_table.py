"""Write src/delta_t/table.rs: Delta T (TT - UT1) from 1948.0 to the IERS prediction horizon.

python3 -I delta_t_table.py historic_deltat.data deltat.data finals2000A.all ../src/delta_t/table.rs

The inputs are USNO files from https://maia.usno.navy.mil/ser7/:
`historic_deltat.data` gives Delta T twice a year with its error up to 1984,
`deltat.data` gives the measured Delta T on the first day of each month from
1973, and `finals2000A.all` gives IERS UT1 - UTC with its error, including the
predictions for about one year. A predicted row becomes Delta T with
TAI - UTC = 37 s, which stays fixed because UTC has no leap seconds from
20 May 2027 (CGPM 2026, Resolution 5).

The table uses the historical rows from 1948.0 to 1973.0, the monthly rows
from 1973-02-01, and then the predicted rows on the first day of each month.
Before 1948.0 the crate uses the spline of Stephenson, Morrison and
Hohenkerk, which meets the historical rows there within 0.02 s. The
backtest below also uses the historical rows from 1799.5. A
monthly row gets an uncertainty of 0.01 s: linear interpolation between monthly
rows differs from the daily IERS values by at most 0.0068 s from 1973 to 2026.
"""
import sys

historic, monthly, finals, out = sys.argv[1:5]


def mjd(year, month, day):
    a = (14 - month) // 12
    y = year + 4800 - a
    m = month + 12 * a - 3
    jdn = day + (153 * m + 2) // 5 + 365 * y + y // 4 - y // 100 + y // 400 - 32045
    return jdn - 2400001.0


TABLE_START_YEAR = 1948.0
rows = []
for line in open(historic).read().splitlines()[2:]:
    fields = line.split()
    year = float(fields[0])
    if 1799.5 <= year <= 1973.0:
        rows.append((51544.5 + (year - 2000.0) * 365.25, float(fields[1]), float(fields[2])))
for line in open(monthly).read().splitlines():
    fields = line.split()
    if len(fields) == 4:
        rows.append((mjd(int(fields[0]), int(fields[1]), int(fields[2])), float(fields[3]), 0.01))
first_predicted = None
for line in open(finals):
    if len(line) < 78 or line[57] != 'P' or line[4:6] != ' 1':
        continue
    year = int(line[0:2])
    day = mjd(year + (2000 if year < 73 else 1900), int(line[2:4]), 1)
    if day <= rows[-1][0]:
        continue
    first_predicted = first_predicted or day
    rows.append((day, 32.184 + 37.0 - float(line[58:68]), float(line[68:78])))
assert all(a[0] < b[0] for a, b in zip(rows, rows[1:]))

# After the last row, Delta T continues with the slope of the last year. The
# error of that rule after n years is the largest error it gave: from each
# month, extrapolated in half-year steps, and compared with the table. Up to
# 80 years the months start in 1900. From 81 to 175 years, which reach past
# 2200, only the months from 1802 give enough history.
YEAR = 365.25


def interpolate(day):
    for (d0, v0, _), (d1, v1, _) in zip(rows, rows[1:]):
        if d0 <= day <= d1:
            return v0 + (v1 - v0) * (day - d0) / (d1 - d0)


def backtest(first_base, years):
    errors = [0.0] * (years + 1)
    base = first_base
    while base + YEAR <= rows[-1][0]:
        value = interpolate(base)
        slope = value - interpolate(base - YEAR)
        for step in range(1, 2 * len(errors) - 1):
            day = base + step * YEAR / 2
            if day > rows[-1][0]:
                break
            error = abs(value + slope * step / 2 - interpolate(day))
            whole = -(-step // 2)
            errors[whole] = max(errors[whole], error)
        base += YEAR / 12
    return errors


errors = backtest(51544.5 - 100 * YEAR, 80) + backtest(51544.5 - 198 * YEAR, 175)[81:]
for n in range(1, len(errors)):
    errors[n] = max(errors[n], errors[n - 1])

rows = [row for row in rows if row[0] >= 51544.5 + (TABLE_START_YEAR - 2000.0) * YEAR]

with open(out, 'w') as f:
    f.write('//! Delta T (TT - UT1) rows, generated by `fixtures/delta_t_table.py`. Do not edit.\n\n')
    f.write('/// Modified Julian date of the first row that is an IERS prediction.\n')
    f.write(f'pub(super) const FIRST_PREDICTED_MJD: f64 = {first_predicted!r};\n\n')
    f.write('/// The largest error, in seconds, of extrapolation from the last row for up\n')
    f.write('/// to n whole years: a backtest over the rows from 1900 up to 80 years, and\n')
    f.write('/// over the rows from 1802 after that.\n')
    f.write('#[rustfmt::skip]\n')
    f.write(f'pub(super) const EXTRAPOLATION_ERROR: [f64; {len(errors)}] = [\n')
    for i in range(0, len(errors), 9):
        f.write('    ' + ' '.join(f'{-(-e * 100 // 1) / 100!r},' for e in errors[i:i + 9]) + '\n')
    f.write('];\n\n')
    f.write('/// Modified Julian date (TT), Delta T in seconds, and its uncertainty in seconds.\n')
    f.write('#[rustfmt::skip]\n')
    f.write('#[allow(clippy::approx_constant, reason = "measured values; one is close to TAU")]\n')
    f.write(f'pub(super) static ROWS: [[f64; 3]; {len(rows)}] = [\n')
    for i in range(0, len(rows), 3):
        f.write('    ' + ' '.join(f'[{d!r}, {v!r}, {e!r}],' for d, v, e in rows[i:i + 3]) + '\n')
    f.write('];\n')
