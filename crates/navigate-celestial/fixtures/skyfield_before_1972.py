"""Write skyfield-before-1972.txt: the apparent Sun and Moon in ITRS axes, 1900 to 1971.

uv run --no-project --python 3.13 --with skyfield==1.53 python -I \
    skyfield_before_1972.py de421.bsp skyfield-before-1972.txt

The input is NAIF `de421.bsp`. Each instant is a UT1 clock reading, which is
what civil time (GMT) gave before 1972. Skyfield finds TT from its built-in
historical Delta T. The ITRS axes have no polar motion.
"""
import sys
from skyfield.api import load, wgs84
from skyfield.framelib import itrs
de421, out = sys.argv[1:3]
ts = load.timescale(builtin=True)
eph = load(de421)
earth, sun, moon = eph['earth'], eph['sun'], eph['moon']
# Geocentre, then observers at 51.4° N 8.1° E, 7.5° S 155.8° E and 4.5° N 114.0° E.
observers = [None, (51.4, 8.1), (-7.5, 155.8), (4.5, 114.0)]
readings = [
    (1900, 1, 2, 0, 0, 0), (1905, 8, 30, 12, 30, 0), (1911, 3, 15, 6, 0, 0),
    (1918, 11, 11, 10, 0, 0), (1926, 6, 21, 18, 45, 0), (1933, 1, 7, 3, 20, 0),
    (1943, 4, 17, 23, 34, 30), (1943, 5, 16, 20, 25, 0), (1944, 12, 10, 2, 0, 0),
    (1950, 9, 23, 15, 0, 0), (1957, 10, 4, 19, 28, 34), (1961, 1, 1, 0, 0, 0),
    (1965, 7, 14, 8, 10, 0), (1969, 7, 20, 20, 17, 40), (1971, 12, 31, 23, 59, 0),
]
with open(out, 'w') as f:
    f.write('# Generated by crates/navigate-celestial/fixtures/skyfield_before_1972.py with Skyfield 1.53.\n')
    f.write('# Apparent directions, ITRS axes with built-in historical Delta T, no polar motion.\n')
    f.write('# ut1 obs_x obs_y obs_z sun_x sun_y sun_z moon_x moon_y moon_z\n')
    for year, month, day, hour, minute, second in readings:
        t = ts.ut1(year, month, day, hour, minute, second)
        label = f'{year:04}-{month:02}-{day:02}T{hour:02}:{minute:02}:{second:02}'
        for place in observers:
            if place is None:
                site, xyz = earth, (0.0, 0.0, 0.0)
            else:
                position = wgs84.latlon(*place)
                site, xyz = earth + position, tuple(float(c) for c in position.itrs_xyz.m)
            row = [label, *(repr(c) for c in xyz)]
            for body in (sun, moon):
                x, y, z = (float(c) for c in site.at(t).observe(body).apparent().frame_xyz(itrs).au)
                n = (x * x + y * y + z * z) ** 0.5
                row += [repr(x / n), repr(y / n), repr(z / n)]
            f.write(' '.join(row) + '\n')
