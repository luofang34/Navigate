//! Write the JPL reference table that bounds the Earth-fixed direction error.
//!
//! ```text
//! cargo run -p navigate-celestial --features anise --example earth_fixed_reference_table -- \
//!     de421.bsp earth_000101_270110_261014.bpc \
//!     crates/navigate-celestial/fixtures/de421-itrf93.txt
//! ```
//!
//! The committed table uses NAIF `de421.bsp` with SHA-256
//! `a20a7139da04cbc462454634918e9a9ca69127044e2cc9d4f9c16e238d2deedc` and
//! `earth_000101_270110_261014.bpc` with SHA-256
//! `c1ba8a074916d9afcfa71a8281e871f89a648c583c9e6c893b1847fb673e15de`.
//! The BPC includes measured UT1 and polar motion. Each row is an observer at
//! rest in ITRF93: `sweep` rows spread over 2000 to 2026, and `horizon` rows
//! are at the 2026-06-14 sunrise test observer. A row gives the label, the
//! TDB seconds from J2000, the observer ECEF position in metres, then the Sun
//! and the Moon as observed with `Correction::VacuumReception`: a unit ITRF93
//! direction and a coordinate range in metres.

use std::{fmt::Write as _, path::PathBuf};

use anise::{
    almanac::Almanac,
    constants::frames::{EARTH_ITRF93, EARTH_J2000},
};
use navigate_celestial::{
    AniseEphemeris, AniseError, Correction, Epoch, FrameId, ObservationError, State, observe_body,
};
use navigate_contract::GeodeticPosition;
use navigate_geodesy::geodetic_to_ecef;

const START_TDB_S: f64 = 43_200.0; // 2000-01-02T00:00:00 TDB
const END_TDB_S: f64 = 844_171_200.0; // 2026-10-01T00:00:00 TDB
const SWEEP_ROWS: u32 = 300;
const GOLDEN_FRACTION: f64 = 0.618_033_988_749_894_9;
const PLASTIC_FRACTION: f64 = 0.754_877_666_246_692_7;
const HORIZON_UTC: [&str; 7] = [
    "2026-06-14T09:10:00 UTC",
    "2026-06-14T09:15:00 UTC",
    "2026-06-14T09:19:00 UTC",
    "2026-06-14T09:19:41 UTC",
    "2026-06-14T09:20:30 UTC",
    "2026-06-14T09:25:00 UTC",
    "2026-06-14T09:30:00 UTC",
];

#[derive(Debug, thiserror::Error)]
enum Error {
    #[error("usage: earth_fixed_reference_table <de421.bsp> <earth.bpc> <output>")]
    Arguments,
    #[error("cannot load kernel {path}")]
    Kernel {
        path: String,
        #[source]
        source: Box<anise::errors::AlmanacError>,
    },
    #[error("cannot parse epoch {0}")]
    Epoch(&'static str, #[source] hifitime::HifitimeError),
    #[error("cannot observe body {body} at TDB {tdb_s} s")]
    Sight {
        body: i32,
        tdb_s: f64,
        #[source]
        source: Box<ObservationError<AniseError>>,
    },
    #[error("cannot rotate to ITRF93 at TDB {tdb_s} s")]
    Rotation {
        tdb_s: f64,
        #[source]
        source: Box<anise::orientations::OrientationError>,
    },
    #[error("cannot format the reference table")]
    Format(#[from] std::fmt::Error),
    #[error("cannot write {}", path.display())]
    Write {
        path: PathBuf,
        #[source]
        source: std::io::Error,
    },
}

fn main() -> Result<(), Error> {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let [spk, bpc, output] = args.as_slice() else {
        return Err(Error::Arguments);
    };
    let mut almanac = Almanac::default();
    for path in [spk, bpc] {
        almanac = almanac.load(path).map_err(|source| Error::Kernel {
            path: path.clone(),
            source: Box::new(source),
        })?;
    }
    let mut table = String::from(
        "# Generated by crates/navigate-celestial/examples/earth_fixed_reference_table.rs\n\
         # from de421.bsp and earth_000101_270110_261014.bpc.\n\
         # label tdb_s obs_x obs_y obs_z sun_x sun_y sun_z sun_range_m moon_x moon_y moon_z moon_range_m\n",
    );
    for row in 0..SWEEP_ROWS {
        let fraction = (f64::from(row) * GOLDEN_FRACTION).fract();
        let tdb_s = (START_TDB_S + fraction * (END_TDB_S - START_TDB_S)).round();
        // Even rows are geocentric. Odd rows are spread over the surface.
        let observer = if row % 2 == 0 {
            [0.0; 3]
        } else {
            let latitude = (2.0 * (f64::from(row) * PLASTIC_FRACTION).fract() - 1.0).asin();
            surface(latitude.to_degrees(), 360.0 * fraction - 180.0)
        };
        write_row(&mut table, &almanac, "sweep", tdb_s, observer)?;
    }
    let horizon_observer = surface(41.072_04, -71.857_33);
    for utc in HORIZON_UTC {
        let epoch: Epoch = utc.parse().map_err(|source| Error::Epoch(utc, source))?;
        write_row(
            &mut table,
            &almanac,
            "horizon",
            epoch.to_tdb_seconds(),
            horizon_observer,
        )?;
    }
    std::fs::write(output, table).map_err(|source| Error::Write {
        path: output.into(),
        source,
    })
}

fn surface(latitude_deg: f64, longitude_deg: f64) -> [f64; 3] {
    let ecef = geodetic_to_ecef(&GeodeticPosition::new(
        latitude_deg.to_radians(),
        longitude_deg.to_radians(),
        0.0,
    ));
    [ecef.x_m, ecef.y_m, ecef.z_m]
}

fn write_row(
    table: &mut String,
    almanac: &Almanac,
    label: &str,
    tdb_s: f64,
    observer_m: [f64; 3],
) -> Result<(), Error> {
    let provider = AniseEphemeris::new(almanac, &[(13000, 3000)]);
    let observer = State {
        position_m: observer_m,
        velocity_m_s: [0.0; 3],
        epoch: Epoch::from_tdb_seconds(tdb_s),
        frame: FrameId::EARTH_ITRF93,
    };
    let [x, y, z] = observer_m;
    write!(table, "{label} {tdb_s:?} {x:?} {y:?} {z:?}")?;
    for body in [10, 301] {
        let sight = observe_body(&provider, observer, body, Correction::VacuumReception).map_err(
            |source| Error::Sight {
                body,
                tdb_s,
                source: Box::new(source),
            },
        )?;
        let rotation = almanac
            .rotate(EARTH_J2000, EARTH_ITRF93, sight.received_at)
            .map_err(|source| Error::Rotation {
                tdb_s,
                source: Box::new(source),
            })?;
        let [x, y, z]: [f64; 3] =
            (rotation.rot_mat * anise::math::Vector3::from(sight.direction)).into();
        write!(table, " {x:?} {y:?} {z:?} {:?}", sight.coordinate_range_m)?;
    }
    table.push('\n');
    Ok(())
}
