//! Write the long-range series tables: VSOP87B Earth and ELP2000-82B Moon.
//!
//! ```text
//! cargo run -p navigate-celestial --example long_range_tables -- \
//!     VSOP87B.ear elp82b_directory crates/navigate-celestial/fixtures/long_range_fit.txt \
//!     crates/navigate-celestial/src/analytic/long_range
//! ```
//!
//! The inputs are IMCCE `VSOP87B.ear` (SHA-256
//! `30a05a74b8bf65aeffffea7d329934b648dfbe186a06f6cce12b0d9403f896bb`), the
//! 36 files ELP1 to ELP36 of ELP2000-82B (IMCCE `/pub/ephem/moon/elp82b`,
//! also CDS VI/79), and the corrections fitted to JPL DE441 in
//! `long_range_fit.txt`, which `examples/long_range_fit.rs` writes. The range
//! is -2000 to 3000, so |t| <= 40 Julian centuries. `long_range/theory.rs`
//! describes the truncation and the changes to ELP82B_2.

#[path = "long_range/theory.rs"]
mod theory;

use std::{
    fmt::Write as _,
    path::{Path, PathBuf},
};

use theory::{ARCSECONDS_PER_RADIAN, Elements, Elp, Error, Fit, MOON_NAMES, ORDER};

const HEADER: &str = "//! Generated by `examples/long_range_tables.rs`. Do not edit.\n\n";
const ATTRIBUTES: &str = "#[rustfmt::skip]\n\
     #[allow(clippy::approx_constant, reason = \"theory coefficients; some phases are close to PI\")]\n";
/// Rows in one generated file, to stay inside the file-size limit.
const CHUNK: usize = 450;

fn main() -> Result<(), Error> {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let [vsop_path, elp_dir, fit_path, out_dir] = args.as_slice() else {
        return Err(
            "usage: long_range_tables <VSOP87B.ear> <elp82b directory> <fit> <output directory>"
                .into(),
        );
    };
    let fit = read_fit(Path::new(fit_path))?;
    let out_dir = Path::new(out_dir);
    write_earth(&theory::vsop(Path::new(vsop_path))?, &fit, out_dir)?;
    write_moon(&Elp::read(Path::new(elp_dir))?, &fit, out_dir)
}

/// Read a fit file: one line for each name, then its coefficients.
fn read_fit(path: &Path) -> Result<Fit, Error> {
    let mut fit = Fit::default();
    for line in std::fs::read_to_string(path)?.lines() {
        let mut fields = line.split_whitespace();
        let Some(name) = fields.next().filter(|name| !name.starts_with('#')) else {
            continue;
        };
        let values: Vec<f64> = fields.map(str::parse).collect::<Result<_, _>>()?;
        let target = match MOON_NAMES.iter().position(|known| *known == name) {
            Some(index) => &mut fit.moon[index],
            None if name == "SUN" => &mut fit.sun,
            None => return Err(format!("{}: unknown name {name}", path.display()).into()),
        };
        *target = values
            .try_into()
            .map_err(|_| format!("{}: {name} needs {} values", path.display(), ORDER + 1))?;
    }
    Ok(fit)
}

fn write(path: PathBuf, text: &str) -> Result<(), Error> {
    std::fs::write(&path, text).map_err(|error| format!("{}: {error}", path.display()).into())
}

fn floats(values: &[f64]) -> String {
    let values: Vec<String> = values.iter().map(|value| format!("{value:?}")).collect();
    format!("[{}]", values.join(", "))
}

/// Write `rows` in files of at most [`CHUNK`] rows and return their module
/// names.
fn write_parts(
    directory: &Path,
    name: &str,
    rows: &[String],
    element: &str,
    doc: &str,
    imports: &str,
) -> Result<Vec<String>, Error> {
    std::fs::create_dir_all(directory)?;
    let mut parts = Vec::new();
    for (index, chunk) in rows.chunks(CHUNK).enumerate() {
        let part = format!("{name}_{}", index + 1);
        let mut text = format!("{HEADER}{imports}/// {doc}\n{ATTRIBUTES}");
        writeln!(
            text,
            "pub(super) static TERMS: [{element}; {}] = [",
            chunk.len()
        )?;
        for row in chunk {
            writeln!(text, "    {row},")?;
        }
        text.push_str("];\n");
        write(directory.join(format!("{part}.rs")), &text)?;
        parts.push(part);
    }
    Ok(parts)
}

fn write_earth(series: &theory::Vsop, fit: &Fit, out_dir: &Path) -> Result<(), Error> {
    let mut modules = Vec::new();
    let mut arrays = Vec::new();
    for (variable, name) in [(1, 'L'), (2, 'B'), (3, 'R')] {
        let mut slices = Vec::new();
        for ((_, power), terms) in series.range((variable, 0)..(variable + 1, 0)) {
            let rows: Vec<String> = terms
                .iter()
                .map(|(a, b, c)| format!("({a:?}, {b:?}, {c:?})"))
                .collect();
            let parts = write_parts(
                &out_dir.join("earth_table"),
                &format!("{}{power}", name.to_ascii_lowercase()),
                &rows,
                "Term",
                &format!("Terms of {name} that multiply tau^{power}."),
                "use super::Term;\n\n",
            )?;
            let [part] = parts.as_slice() else {
                return Err(format!("{name}{power} needs {} files", parts.len()).into());
            };
            slices.push(format!("&{part}::TERMS"));
            modules.push(part.clone());
        }
        arrays.push((name, slices));
    }
    modules.sort();
    let mut text = format!("{HEADER}use super::Term;\n\n");
    for module in &modules {
        writeln!(text, "mod {module};")?;
    }
    text.push('\n');
    for (name, slices) in arrays {
        writeln!(
            text,
            "/// Terms of {name}, by power of the time in millennia.\n#[rustfmt::skip]\n\
             pub(super) static {name}: [&[Term]; {}] = [{}];\n",
            slices.len(),
            slices.join(", ")
        )?;
    }
    let correction: Vec<f64> = fit.sun.iter().map(|c| c / ARCSECONDS_PER_RADIAN).collect();
    writeln!(
        text,
        "/// Correction to the VSOP87B longitude, fitted to DE441: radians by power\n\
         /// of TDB Julian centuries from J2000.\n#[rustfmt::skip]\n\
         pub(super) const LONGITUDE_CORRECTION: [f64; {}] = {};",
        correction.len(),
        floats(&correction)
    )?;
    write(out_dir.join("earth_table.rs"), &text)
}

fn write_moon(elp: &Elp, fit: &Fit, out_dir: &Path) -> Result<(), Error> {
    let elements = Elements::new(fit);
    let terms = elp.terms(&elements);
    let moon_dir = out_dir.join("moon");
    for (variable, name) in ["longitude", "latitude", "distance"]
        .into_iter()
        .enumerate()
    {
        let unit = if variable == 2 {
            "kilometres"
        } else {
            "arcseconds"
        };
        let directory = moon_dir.join(name);
        let main_rows: Vec<String> = terms.main[variable]
            .iter()
            .map(|(amplitude, phase)| format!("({amplitude:?}, {})", floats(phase)))
            .collect();
        let perturbation_rows: Vec<String> = terms.perturbation[variable]
            .iter()
            .map(|(amplitude, power, phase)| format!("({amplitude:?}, {power}, {})", floats(phase)))
            .collect();
        let main_parts = write_parts(
            &directory,
            "main",
            &main_rows,
            "(f64, [f64; 5])",
            &format!(
                "Main problem: amplitude in {unit}, then the phase in radians by power of `t`."
            ),
            "",
        )?;
        let perturbation_parts = write_parts(
            &directory,
            "perturbation",
            &perturbation_rows,
            "(f64, i32, [f64; 5])",
            &format!(
                "Perturbations: amplitude in {unit}, the power of `t` that multiplies it,\n\
                 /// then the phase in radians by power of `t`."
            ),
            "",
        )?;
        let mut text = String::from(HEADER);
        for module in main_parts.iter().chain(&perturbation_parts) {
            writeln!(text, "mod {module};")?;
        }
        text.push('\n');
        if variable == 0 {
            writeln!(
                text,
                "/// Mean longitude W1 in radians, by power of `t`, fitted to DE441.\n{ATTRIBUTES}\
                 pub(super) const MEAN_LONGITUDE: [f64; 5] = {};\n",
                floats(&elements.w[0])
            )?;
        }
        let list = |parts: &[String]| {
            parts
                .iter()
                .map(|part| format!("&{part}::TERMS"))
                .collect::<Vec<_>>()
                .join(", ")
        };
        writeln!(
            text,
            "/// Main problem, in parts.\n#[rustfmt::skip]\n\
             pub(super) static MAIN: [&[(f64, [f64; 5])]; {}] = [{}];\n\n\
             /// Perturbations, in parts.\n#[rustfmt::skip]\n\
             pub(super) static PERTURBATION: [&[(f64, i32, [f64; 5])]; {}] = [{}];",
            main_parts.len(),
            list(&main_parts),
            perturbation_parts.len(),
            list(&perturbation_parts)
        )?;
        write(moon_dir.join(format!("{name}.rs")), &text)?;
    }
    Ok(())
}
