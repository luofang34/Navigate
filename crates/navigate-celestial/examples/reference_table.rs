//! Write the JPL reference table that bounds the analytic ephemeris error.
//!
//! ```text
//! cargo run -p navigate-celestial --features anise --example reference_table -- \
//!     de421.bsp 1900 2050 crates/navigate-celestial/fixtures/de421-geocentric.txt
//! cargo run -p navigate-celestial --features anise --example reference_table -- \
//!     de440.bsp 1800 2200 crates/navigate-celestial/fixtures/de440-geocentric.txt
//! ```
//!
//! The committed tables use NAIF `de421.bsp` with SHA-256
//! `a20a7139da04cbc462454634918e9a9ca69127044e2cc9d4f9c16e238d2deedc` and
//! `de440.bsp` with SHA-256
//! `a4ce9bf9b3282becc9f4b2ac3cebe03a2ae7599981aabd7265fd8482fff7c4b5`. The
//! epochs span 1 January 00:00 TDB of the first year to the same instant of
//! the last year. Each row is one geocentric observer at rest in J2000 axes. It gives the
//! TDB seconds from J2000, then the Sun and the Moon as observed with
//! `Correction::VacuumReception`: a unit direction and a coordinate range in
//! metres.

use std::{fmt::Write as _, path::PathBuf};

use anise::almanac::Almanac;
use navigate_celestial::{
    AniseEphemeris, AniseError, Correction, Epoch, FrameId, ObservationError, State, TimeScale,
    observe_body,
};

const ROWS: u32 = 400;
const GOLDEN_FRACTION: f64 = 0.618_033_988_749_894_9;

#[derive(Debug, thiserror::Error)]
enum Error {
    #[error("usage: reference_table <kernel.bsp> <first year> <last year> <output>")]
    Arguments,
    #[error("cannot load kernel {path}")]
    Kernel {
        path: String,
        #[source]
        source: Box<anise::errors::AlmanacError>,
    },
    #[error("cannot observe body {body} at TDB {tdb_s} s")]
    Sight {
        body: i32,
        tdb_s: f64,
        #[source]
        source: Box<ObservationError<AniseError>>,
    },
    #[error("cannot format the reference table")]
    Format(#[from] std::fmt::Error),
    #[error("cannot write {}", path.display())]
    Write {
        path: PathBuf,
        #[source]
        source: std::io::Error,
    },
}

fn main() -> Result<(), Error> {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let [kernel, first, last, output] = args.as_slice() else {
        return Err(Error::Arguments);
    };
    let [start_tdb_s, end_tdb_s] = [first, last].map(|year| {
        year.parse::<i32>().map(|year| {
            Epoch::from_gregorian(year, 1, 1, 0, 0, 0, 0, TimeScale::TDB).to_tdb_seconds()
        })
    });
    let (Ok(start_tdb_s), Ok(end_tdb_s)) = (start_tdb_s, end_tdb_s) else {
        return Err(Error::Arguments);
    };
    let name = std::path::Path::new(kernel).file_name().map_or_else(
        || kernel.clone(),
        |name| name.to_string_lossy().into_owned(),
    );
    let almanac = Almanac::default()
        .load(kernel)
        .map_err(|source| Error::Kernel {
            path: kernel.clone(),
            source: Box::new(source),
        })?;
    let provider = AniseEphemeris::new(&almanac, &[]);
    let mut table = format!(
        "# Generated by crates/navigate-celestial/examples/reference_table.rs from {name}.\n\
         # tdb_s sun_x sun_y sun_z sun_range_m moon_x moon_y moon_z moon_range_m\n",
    );
    for row in 0..ROWS {
        // A golden-ratio sequence spreads the epochs over the orbital phases.
        let fraction = (f64::from(row) * GOLDEN_FRACTION).fract();
        let tdb_s = (start_tdb_s + fraction * (end_tdb_s - start_tdb_s)).round();
        let observer = State {
            position_m: [0.0; 3],
            velocity_m_s: [0.0; 3],
            epoch: Epoch::from_tdb_seconds(tdb_s),
            frame: FrameId {
                center: 399,
                orientation: 1,
            },
        };
        write!(table, "{tdb_s:?}")?;
        for body in [10, 301] {
            let sight = observe_body(&provider, observer, body, Correction::VacuumReception)
                .map_err(|source| Error::Sight {
                    body,
                    tdb_s,
                    source: Box::new(source),
                })?;
            let [x, y, z] = sight.direction;
            write!(table, " {x:?} {y:?} {z:?} {:?}", sight.coordinate_range_m)?;
        }
        table.push('\n');
    }
    std::fs::write(output, table).map_err(|source| Error::Write {
        path: output.into(),
        source,
    })
}
