import assert from 'node:assert/strict';
import {emitDatasetReport} from '../webapp/qa-dataset-report.js';
const trace=Array.from({length:2000},()=>({ground:'raw-ground-evidence',position:[1,2,3]}));
const hypotheses=Array.from({length:128},(_,candidate_id)=>({candidate_id,accepted:candidate_id===7||candidate_id===91,geometry_covariance:Array.from({length:6},()=>Array(6).fill(0)),reference_pose:{position_enu_m:[1,2,3]},reason:'per-candidate-geometry-evidence'}));
const report={cases:[{name:'observation',geometric_acceptance:false,acquisition_trace:trace,retrieval_trace:{ranks:Array.from({length:42000},()=>({reference_index:0,query_index:0})),references:[{key:"raw-retrieval-evidence"}]},hypotheses}]},output={};
let saved;
await emitDatasetReport(report,'complete',output,async(_url,request)=>{saved=JSON.parse(request.body);return {ok:true}});
assert.equal(saved.cases[0].acquisition_trace.length,2000,'the local evidence export retains correspondences');
assert.equal(saved.phase,'complete');
assert.equal(saved.cases[0].retrieval_trace.ranks.length,42000);
assert.equal(output.textContent.includes('raw-retrieval-evidence'),false);
assert.deepEqual(saved.cases[0].hypotheses,hypotheses,'the export keeps each geometric alternative and its provenance');
const visible=JSON.parse(output.textContent);
assert.equal(visible.cases[0].trace_comparisons,2000);
assert.equal(visible.cases[0].retrieval_pairs,42000);
assert.equal(visible.cases[0].geometric_acceptance,false);
assert.equal(visible.cases[0].evaluated_hypotheses,128);
assert.deepEqual(visible.cases[0].accepted_candidate_ids,[7,91]);
assert.equal(output.textContent.includes('per-candidate-geometry-evidence'),false);
assert.equal(output.textContent.includes('raw-ground-evidence'),false,'large traces do not enter the browser document or accessibility tree');
assert.ok(output.textContent.length<1000);
await assert.rejects(emitDatasetReport(report,'complete',output,async()=>({ok:false,status:413})),/413/);
console.info('Diagnostic rendering stays compact, preserves exported evidence, and rejects failed uploads');
